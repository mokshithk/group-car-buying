import React, { createContext, useContext, useEffect, useState, useCallback } from 'react';
import { supabase, isSupabaseConfigured } from '@/lib/supabase';
import { isAdminRole, isSuperAdminRole } from '@/lib/adminHelpers';
import { Profile, Dealership, UserRole, DealershipStatus } from '@/types';
import type { User } from '@supabase/supabase-js';

export interface BuyerRegistrationData {
  fullName: string;
  email: string;
  phone: string;
  districtId: string;
  password: string;
  consentShareDetails: boolean;
}

export interface DealerRegistrationData {
  dealershipName: string;
  ownerName: string;
  email: string;
  phone: string;
  districtId: string;
  address: string;
  gstNumber: string;
  brands: string[];
  password: string;
}

export interface OtpDispatchResult {
  success: boolean;
  error?: string;
  alreadyRegistered?: boolean;
  devOtp?: string;
  smtpError?: string;
  channel?: string;
  challengeToken?: string;
}

interface AuthContextType {
  user: User | null;
  profile: Profile | null;
  dealership: Dealership | null;
  role: UserRole | null;
  isAdmin: boolean;
  isSuperAdmin: boolean;
  mustChangePassword: boolean;
  isLoading: boolean;
  login: (email: string, password: string) => Promise<{
    success: boolean;
    error?: string;
    role?: UserRole;
    dealershipStatus?: DealershipStatus;
    mustChangePassword?: boolean;
    isUnconfirmedEmail?: boolean;
  }>;
  reauthenticate: (password: string) => Promise<{ success: boolean; error?: string }>;
  completeAdminPasswordUpdate: (newPassword: string, isInitialForced?: boolean) => Promise<{ success: boolean; error?: string }>;
  requestSignupOtp: (email: string, fullName?: string) => Promise<OtpDispatchResult>;
  registerBuyer: (data: BuyerRegistrationData) => Promise<{ success: boolean; error?: string; requiresEmailConfirmation?: boolean }>;
  registerDealer: (data: DealerRegistrationData) => Promise<{ success: boolean; error?: string; requiresEmailConfirmation?: boolean }>;
  logout: () => Promise<void>;
  refreshProfile: () => Promise<{ profile: Profile | null; dealership: Dealership | null } | undefined>;
}

const AuthContext = createContext<AuthContextType | undefined>(undefined);

export function AuthProvider({ children }: { children: React.ReactNode }) {
  const [user, setUser] = useState<User | null>(null);
  const [profile, setProfile] = useState<Profile | null>(null);
  const [dealership, setDealership] = useState<Dealership | null>(null);
  const [isLoading, setIsLoading] = useState(() => isSupabaseConfigured());

  const fetchProfileAndDealership = useCallback(async (userId: string): Promise<{ profile: Profile | null; dealership: Dealership | null }> => {
    try {
      if (!isSupabaseConfigured()) {
        return { profile: null, dealership: null };
      }
      const { data: prof, error: profError } = await supabase
        .from('profiles')
        .select('*')
        .eq('id', userId)
        .maybeSingle();

      if (profError) throw profError;

      if (prof) {
        const p = prof as Profile;
        setProfile(p);

        let dData: Dealership | null = null;
        if (p.role === 'dealer') {
          const { data: dealerUser } = await supabase
            .from('dealer_users')
            .select('dealership_id')
            .eq('user_id', userId)
            .maybeSingle();

          let targetId = dealerUser?.dealership_id;
          if (!targetId) {
            const { data: sessionData } = await supabase.auth.getSession();
            const userEmail = sessionData?.session?.user?.email;
            if (userEmail) {
              const { data: directD } = await supabase
                .from('dealerships')
                .select('id')
                .eq('contact_email', userEmail)
                .maybeSingle();
              targetId = directD?.id;
            }
          }

          if (targetId) {
            const { data: dealerData } = await supabase
              .from('dealerships')
              .select('*')
              .eq('id', targetId)
              .maybeSingle();

            if (dealerData) {
              dData = dealerData as Dealership;
              setDealership(dData);
            }
          }
        }
        return { profile: p, dealership: dData };
      } else {
        // Self-healing fallback: If user row in public.profiles table is not yet generated by trigger,
        // construct profile from auth session user_metadata and auto-insert into public.profiles
        const { data: sessionData } = await supabase.auth.getSession();
        const currentUser = sessionData?.session?.user;
        if (currentUser && currentUser.id === userId) {
          const meta = currentUser.user_metadata || {};
          const fallbackProfile: Profile = {
            id: userId,
            role: (meta.role as UserRole) || 'buyer',
            full_name: meta.full_name || currentUser.email?.split('@')[0] || 'User',
            phone: meta.phone || null,
            district_id: meta.district_id || 'd1111111-1111-1111-1111-111111111101',
            consent_share_details: meta.consent_share_details ?? true,
            created_at: currentUser.created_at || new Date().toISOString(),
            updated_at: new Date().toISOString(),
          };

          try {
            await supabase.from('profiles').insert(fallbackProfile);
          } catch (_) {
            // Ignore insert error if RLS blocks, state profile will still be set
          }

          setProfile(fallbackProfile);
          return { profile: fallbackProfile, dealership: null };
        }
      }
    } catch (err) {
      if (import.meta.env.DEV) {
        console.error('Error fetching profile and dealership:', err);
      }
    }
    return { profile: null, dealership: null };
  }, []);

  useEffect(() => {
    if (!isSupabaseConfigured()) {
      return;
    }

    supabase.auth.getSession().then(async ({ data: { session } }) => {
      setUser(session?.user ?? null);
      if (session?.user) {
        await fetchProfileAndDealership(session.user.id);
      }
      setIsLoading(false);
    });

    const {
      data: { subscription },
    } = supabase.auth.onAuthStateChange(async (_event, session) => {
      setUser(session?.user ?? null);
      if (session?.user) {
        await fetchProfileAndDealership(session.user.id);
      } else {
        setProfile(null);
        setDealership(null);
      }
      setIsLoading(false);
    });

    return () => subscription.unsubscribe();
  }, [fetchProfileAndDealership]);

  const login = async (email: string, password: string) => {
    setIsLoading(true);
    try {
      if (!isSupabaseConfigured()) {
        return { success: false, error: 'Database backend is not configured.' };
      }

      const { data, error } = await supabase.auth.signInWithPassword({ email, password });
      if (error) {
        const errorMsg = error.message;
        const isEmailNotConfirmed =
          errorMsg.toLowerCase().includes('email not confirmed') ||
          (error as any).code === 'email_not_confirmed';

        if (import.meta.env.DEV) {
          console.error('Supabase signInWithPassword error:', error);
        }

        if (isEmailNotConfirmed) {
          return {
            success: false,
            error: 'Your email address has not been verified yet.',
            isUnconfirmedEmail: true,
          };
        }

        return {
          success: false,
          error: errorMsg.toLowerCase().includes('invalid login credentials')
            ? 'Invalid email or password.'
            : errorMsg,
        };
      }

      if (data.user) {
        const { data: prof } = await supabase
          .from('profiles')
          .select('role, status, suspension_reason, must_change_password')
          .eq('id', data.user.id)
          .maybeSingle();

        if (prof?.status === 'SUSPENDED' || prof?.status === 'DEACTIVATED') {
          await supabase.auth.signOut();
          setUser(null);
          setProfile(null);
          setDealership(null);
          return {
            success: false,
            error:
              prof.suspension_reason ||
              `Your account has been ${prof.status.toLowerCase()}. Please contact support@autogroup.in.`,
          };
        }

        try {
          await supabase.rpc('sync_user_sign_in');
        } catch {
          // Ignore if migration 006 not yet applied
        }

        await fetchProfileAndDealership(data.user.id);

        const role = (prof?.role as UserRole) || 'buyer';
        const mustChangePassword = Boolean(prof?.must_change_password);
        let dealershipStatus: DealershipStatus | undefined;

        if (role === 'dealer') {
          const { data: du } = await supabase
            .from('dealer_users')
            .select('dealership_id')
            .eq('user_id', data.user.id)
            .maybeSingle();

          let dId = du?.dealership_id;
          if (!dId && data.user.email) {
            const { data: directD } = await supabase
              .from('dealerships')
              .select('id')
              .eq('contact_email', data.user.email)
              .maybeSingle();
            dId = directD?.id;
          }

          if (dId) {
            const { data: dRow } = await supabase
              .from('dealerships')
              .select('status')
              .eq('id', dId)
              .maybeSingle();
            dealershipStatus = dRow?.status as DealershipStatus;
          }
        }

        return { success: true, role, dealershipStatus, mustChangePassword };
      }
      return { success: false, error: 'Login failed. Please check credentials.' };
    } catch (err: unknown) {
      if (import.meta.env.DEV) {
        console.error('Login error:', err);
      }
      const msg = err instanceof Error ? err.message : 'Login failed';
      return { success: false, error: msg };
    } finally {
      setIsLoading(false);
    }
  };

  const reauthenticate = async (password: string): Promise<{ success: boolean; error?: string }> => {
    const email = user?.email || profile?.email;
    if (!email) {
      return { success: false, error: 'No signed-in user email found for re-authentication.' };
    }
    if (!password) {
      return { success: false, error: 'Please enter your current password to confirm.' };
    }
    const { error } = await supabase.auth.signInWithPassword({ email, password });
    if (error) {
      return {
        success: false,
        error: error.message.toLowerCase().includes('invalid login credentials')
          ? 'Incorrect password. Re-authentication failed.'
          : error.message,
      };
    }
    return { success: true };
  };

  const completeAdminPasswordUpdate = async (
    newPassword: string,
    isInitialForced: boolean = false
  ): Promise<{ success: boolean; error?: string }> => {
    const { error: updateErr } = await supabase.auth.updateUser({ password: newPassword });
    if (updateErr) {
      return { success: false, error: updateErr.message };
    }

    const { error: rpcErr } = await supabase.rpc('admin_complete_password_change', {
      p_is_initial_forced: isInitialForced,
    });
    if (rpcErr) {
      return { success: false, error: rpcErr.message };
    }

    const uid = user?.id;
    if (uid) {
      await fetchProfileAndDealership(uid);
    } else {
      const { data: { session } } = await supabase.auth.getSession();
      if (session?.user?.id) {
        await fetchProfileAndDealership(session.user.id);
      }
    }
    return { success: true };
  };

  const requestSignupOtp = async (email: string, fullName?: string): Promise<OtpDispatchResult> => {
    try {
      const cleanEmail = email.trim().toLowerCase();
      if (!cleanEmail || !cleanEmail.includes('@')) {
        return { success: false, error: 'Please enter a valid email address.' };
      }

      if (isSupabaseConfigured()) {
        try {
          const { data: isRegistered, error: rpcErr } = await supabase.rpc('is_email_registered', {
            p_email: cleanEmail,
          });
          if (!rpcErr && isRegistered === true) {
            return {
              success: false,
              alreadyRegistered: true,
              error: 'This email is already registered. Please sign in or reset your password.',
            };
          }
        } catch {
          // Proceed if RPC check is unavailable
        }
      }

      const otpRes = await fetch('/api/auth/send-otp', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ email: cleanEmail, type: 'signup', fullName }),
      });

      const otpData = await otpRes.json().catch(() => null);
      if (!otpRes.ok || !otpData?.success) {
        return {
          success: false,
          error: otpData?.error || 'Failed to dispatch OTP email. Please verify email server configuration.',
        };
      }

      return {
        success: true,
        devOtp: otpData.devOtp,
        smtpError: otpData.smtpError,
        channel: otpData.channel,
        challengeToken: otpData.challengeToken,
      };
    } catch (err: unknown) {
      const msg = err instanceof Error ? err.message : 'Unable to send OTP verification code.';
      return { success: false, error: msg };
    }
  };

  const registerBuyer = async (data: BuyerRegistrationData): Promise<{
    success: boolean;
    error?: string;
    requiresEmailConfirmation?: boolean;
  }> => {
    setIsLoading(true);
    try {
      if (!isSupabaseConfigured()) {
        return { success: false, error: 'Database backend is not configured.' };
      }

      const { data: authData, error: authError } = await supabase.auth.signUp({
        email: data.email.trim().toLowerCase(),
        password: data.password,
        options: {
          data: {
            role: 'buyer',
            full_name: data.fullName,
            phone: data.phone,
            district_id: data.districtId,
            consent_share_details: data.consentShareDetails,
          },
        },
      });

      if (authError) {
        if (import.meta.env.DEV) {
          console.error('Supabase signUp buyer error:', authError);
        }
        let msg = authError.message;
        if (msg.includes('rate limit') || (authError as any).code === 'over_email_send_rate_limit') {
          msg = 'Email rate limit exceeded. Please wait a few moments before trying again.';
        } else if (msg.includes('invalid') || (authError as any).code === 'email_address_invalid') {
          msg = 'Please enter a valid email address.';
        } else if ((authError as any).code === 'user_already_exists' || msg.toLowerCase().includes('already registered')) {
          const signRes = await supabase.auth.signInWithPassword({
            email: data.email.trim().toLowerCase(),
            password: data.password,
          });
          if (signRes.data?.session) {
            await fetchProfileAndDealership(signRes.data.user.id);
            return { success: true, requiresEmailConfirmation: false };
          }
          return {
            success: false,
            error: 'This email is already registered. Please sign in or reset your password.',
          };
        }
        return { success: false, error: msg };
      }

      if (!authData.user) return { success: false, error: 'User creation failed.' };

      // Requirement D.5: If user exists and is already verified, identities array is empty
      if (authData.user.identities && authData.user.identities.length === 0) {
        const signRes = await supabase.auth.signInWithPassword({
          email: data.email.trim().toLowerCase(),
          password: data.password,
        });
        if (signRes.data?.session) {
          await fetchProfileAndDealership(signRes.data.user.id);
          return { success: true, requiresEmailConfirmation: false };
        }
        return {
          success: false,
          error: 'This email is already registered. Please sign in.',
        };
      }

      if (authData.session) {
        await fetchProfileAndDealership(authData.user.id);
        return { success: true, requiresEmailConfirmation: false };
      }

      // Sign in explicitly if session wasn't attached directly
      const signInRes = await supabase.auth.signInWithPassword({
        email: data.email.trim().toLowerCase(),
        password: data.password,
      });
      if (signInRes.data?.session) {
        await fetchProfileAndDealership(signInRes.data.user.id);
        return { success: true, requiresEmailConfirmation: false };
      }

      return { success: true, requiresEmailConfirmation: true };
    } catch (err: unknown) {
      if (import.meta.env.DEV) {
        console.error('Buyer registration exception:', err);
      }
      const msg = err instanceof Error ? err.message : 'Registration failed';
      return { success: false, error: msg };
    } finally {
      setIsLoading(false);
    }
  };

  const registerDealer = async (data: DealerRegistrationData): Promise<{
    success: boolean;
    error?: string;
    requiresEmailConfirmation?: boolean;
  }> => {
    setIsLoading(true);
    try {
      if (!isSupabaseConfigured()) {
        return { success: false, error: 'Database backend is not configured.' };
      }

      const { data: authData, error: authError } = await supabase.auth.signUp({
        email: data.email.trim().toLowerCase(),
        password: data.password,
        options: {
          data: {
            role: 'dealer',
            full_name: data.ownerName,
            phone: data.phone,
            district_id: data.districtId,
            consent_share_details: true,
            dealership_name: data.dealershipName,
            dealership_address: data.address,
            gst_number: data.gstNumber,
            brands: data.brands,
          },
        },
      });

      if (authError) {
        if (import.meta.env.DEV) {
          console.error('Supabase signUp dealer error:', authError);
        }
        let msg = authError.message;
        if (msg.includes('rate limit') || (authError as any).code === 'over_email_send_rate_limit') {
          msg = 'Email rate limit exceeded. Please wait a few moments before trying again.';
        } else if (msg.includes('invalid') || (authError as any).code === 'email_address_invalid') {
          msg = 'Please enter a valid email address.';
        } else if ((authError as any).code === 'user_already_exists' || msg.toLowerCase().includes('already registered')) {
          const signRes = await supabase.auth.signInWithPassword({
            email: data.email.trim().toLowerCase(),
            password: data.password,
          });
          if (signRes.data?.session) {
            await fetchProfileAndDealership(signRes.data.user.id);
            return { success: true, requiresEmailConfirmation: false };
          }
          return {
            success: false,
            error: 'This email is already registered. Please sign in.',
          };
        }
        return { success: false, error: msg };
      }

      if (!authData.user) return { success: false, error: 'Dealer account creation failed.' };

      // Requirement D.5: If user exists and is already verified, identities array is empty
      if (authData.user.identities && authData.user.identities.length === 0) {
        const signRes = await supabase.auth.signInWithPassword({
          email: data.email.trim().toLowerCase(),
          password: data.password,
        });
        if (signRes.data?.session) {
          await fetchProfileAndDealership(signRes.data.user.id);
          return { success: true, requiresEmailConfirmation: false };
        }
        return {
          success: false,
          error: 'This email is already registered. Please sign in.',
        };
      }

      if (authData.session) {
        await fetchProfileAndDealership(authData.user.id);
        return { success: true, requiresEmailConfirmation: false };
      }

      const signInRes = await supabase.auth.signInWithPassword({
        email: data.email.trim().toLowerCase(),
        password: data.password,
      });
      if (signInRes.data?.session) {
        await fetchProfileAndDealership(signInRes.data.user.id);
        return { success: true, requiresEmailConfirmation: false };
      }

      return { success: true, requiresEmailConfirmation: true };
    } catch (err: unknown) {
      if (import.meta.env.DEV) {
        console.error('Dealer registration exception:', err);
      }
      const msg = err instanceof Error ? err.message : 'Dealer registration failed';
      return { success: false, error: msg };
    } finally {
      setIsLoading(false);
    }
  };

  const logout = async () => {
    if (isSupabaseConfigured()) {
      await supabase.auth.signOut();
    }
    setUser(null);
    setProfile(null);
    setDealership(null);
  };

  const refreshProfile = async (): Promise<{ profile: Profile | null; dealership: Dealership | null } | undefined> => {
    let currentUserId = user?.id;
    if (!currentUserId) {
      const { data: { session } } = await supabase.auth.getSession();
      currentUserId = session?.user?.id;
      if (session?.user) {
        setUser(session.user);
      }
    }
    if (currentUserId) {
      return await fetchProfileAndDealership(currentUserId);
    }
    return undefined;
  };

  return (
    <AuthContext.Provider
      value={{
        user,
        profile,
        dealership,
        role: profile?.role ?? null,
        isAdmin: isAdminRole(profile?.role),
        isSuperAdmin: isSuperAdminRole(profile?.role),
        mustChangePassword: Boolean(profile?.must_change_password),
        isLoading,
        login,
        reauthenticate,
        completeAdminPasswordUpdate,
        requestSignupOtp,
        registerBuyer,
        registerDealer,
        logout,
        refreshProfile,
      }}
    >
      {children}
    </AuthContext.Provider>
  );
}

export function useAuth() {
  const context = useContext(AuthContext);
  if (!context) {
    throw new Error('useAuth must be used within an AuthProvider');
  }
  return context;
}
